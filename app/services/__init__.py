"""服务层包：业务编排与事务边界。

包含七个服务，按职责分层：
- ``log_service``：全链路日志（其余服务都依赖它，最先实现）；
- ``task_service``：审批任务拉取、去重、状态流转、阻塞与重试；
- ``attachment_service``：附件下载、落盘、校验、元数据；
- ``parse_service``：解析编排、阻塞判定、解析结果入库；
- ``review_service``：规则审查编排、命中入库；
- ``result_service``：审查结果入库、回写文本生成；
- ``comment_service``：评论回写、幂等控制、回写日志。

分层约定：
1. **事务边界在服务层**。每个公开服务函数自己开 ``session_scope()`` 并提交，
   因此单步失败不会回滚已完成的步骤（例如解析成功但审查失败时，解析结果仍保留）。
2. **跨服务只传 ID，不传 ORM 对象**。ORM 对象与会话绑定，跨会话使用会拿到过期数据。
3. **服务层不做输入格式校验**（那是工具层的事），只做业务约束校验
   （如"只有 blocked 任务才能重试"）。
4. **异常向上抛**，由工具层决定如何呈现；服务层只负责把失败原因写进数据库。
"""
